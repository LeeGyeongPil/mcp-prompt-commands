import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { test } from "node:test";
import { findByNameOrId, normalizeName, resolveNames } from "../src/names.js";
import { runCli, tmpDir, writeStdioConfig } from "./helpers.js";

test("names: normalize and resolve collisions", (t) => {
  assert.equal(normalizeName("release notes"), "release-notes");
  assert.equal(normalizeName("  Weird // Name!! "), "weird-name");
  assert.equal(normalizeName("keep_under_score-and-dash"), "keep_under_score-and-dash");
  assert.equal(normalizeName("???"), "unnamed");

  // Sorted by original name: "Release Notes" < "release notes" < "release_notes".
  const r = resolveNames(["release notes", "Release Notes", "release_notes"]);
  assert.deepEqual(
    r.map((x) => [x.original, x.id, x.collided]),
    [
      ["release notes", "release-notes-2", true],
      ["Release Notes", "release-notes", false],
      ["release_notes", "release_notes", false],
    ],
  );
  assert.equal(findByNameOrId([{ name: "release notes" }, { name: "Release Notes" }], "release-notes-2")?.name, "release notes");
  assert.equal(findByNameOrId([{ name: "release notes" }], "release notes")?.name, "release notes");

  // End to end: the collision is warned about and both files exist.
  const dir = tmpDir(t);
  writeStdioConfig(dir, "dupes");
  const g = runCli(["generate", "--config", "servers.json", "--out", "out", "--bin", "echo"], { cwd: dir });
  assert.equal(g.code, 0, g.stderr);
  assert.match(g.stderr, /collides after normalization and was named "release-notes-2"/);
  for (const f of ["release-notes.md", "release-notes-2.md", "release_notes.md"]) {
    assert.ok(readFileSync(join(dir, "out", "commands", "mock", f), "utf8").includes("generated by mcp-prompt-commands"), f);
  }
  const got = runCli(["get", "mock", "release-notes-2", "--config", "servers.json"], { cwd: dir });
  assert.equal(got.stdout.trim(), "release notes");
});
