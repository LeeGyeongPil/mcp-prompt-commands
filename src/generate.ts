import { argIdents, safeArgName } from "./args.js";
import type { Format, Mode, PromptDef } from "./types.js";

/** First line of generated text; files without it are treated as user-authored and never overwritten. */
export const GENERATED_MARKER = "<!-- generated by mcp-prompt-commands; do not edit -->";

export interface BuildInput {
  serverId: string;
  promptId: string;
  /** Directory name for the skills format (`<server>-<prompt>`, collision-resolved). */
  skillDir: string;
  def: PromptDef;
  format: Format;
  mode: Mode;
  bin: string;
  allowedTools: boolean;
  /** Extra CLI arguments baked into the `!` line, for example `--config examples/mcp.json`. */
  extraArgs: string[];
  /** Rendered prompt with marker values in place of arguments (static mode). */
  template: string | undefined;
  /** The server refused the marker values, so a template could not be captured. */
  rejected: boolean;
}

export interface BuiltFile {
  /** Path relative to the output directory, with "/" separators. */
  path: string;
  content: string;
  /** The mode actually used (a rejected template turns live/static into agent). */
  mode: Mode;
}

function oneLine(text: string, max: number): string {
  const flat = text.replace(/\s+/g, " ").trim();
  return flat.length > max ? `${flat.slice(0, max - 1)}…` : flat;
}

/**
 * Makes server-provided text inert for Claude Code's file rendering:
 *  - `$1`, `$ARGUMENTS` and `$<declared name>` would be substituted, so they get a backslash;
 *  - an inline `!` followed by a backtick, or a fenced block opened with `!`, would run a shell
 *    command, so a space is inserted to break the syntax.
 */
export function neutralizeHostSyntax(text: string, idents: string[]): string {
  const names = ["ARGUMENTS", ...idents.map((i) => i.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"))];
  const dollar = new RegExp(`\\$(?=\\d|${names.join("|")})`, "g");
  return text
    .replace(dollar, "\\$")
    .replace(/(^|\s)!`/g, "$1! `")
    .replace(/(`{3,})!/g, "$1 !");
}

/** Whether text still contains something Claude Code would run or substitute. */
export function hasActiveShell(text: string): boolean {
  return /(^|\s)!`/.test(text) || /`{3,}!/.test(text);
}

function frontmatter(input: BuildInput, effective: Mode, idents: string[], hint: string): string {
  const { def } = input;
  const description = oneLine(def.description ?? def.title ?? `MCP prompt ${input.promptId} from ${input.serverId}`, 250);
  const lines = ["---"];
  if (input.format === "skills") lines.push(`name: ${input.skillDir}`);
  lines.push(`description: ${JSON.stringify(description)}`);
  if (def.arguments.length > 0) {
    lines.push(`argument-hint: ${JSON.stringify(hint)}`);
    lines.push(`arguments: [${idents.join(", ")}]`);
  }
  if (effective !== "static" && input.allowedTools) {
    lines.push(`allowed-tools: ${JSON.stringify(`Bash(${input.bin} get *)`)}`);
  }
  lines.push("---");
  return lines.join("\n");
}

function argumentList(def: PromptDef, idents: string[]): string {
  const rows = def.arguments.map(
    (a, i) => `- ${safeArgName(a.name)} (${a.required ? "required" : "optional"}): $${idents[i] ?? ""}`,
  );
  return rows.join("\n");
}

function cliPrefix(input: BuildInput): string {
  return `${input.bin} get ${input.serverId} ${input.promptId}${input.extraArgs.map((a) => ` ${a}`).join("")}`;
}

function liveBody(input: BuildInput, idents: string[]): string {
  const { def } = input;
  const out = [
    GENERATED_MARKER,
    `This command runs the MCP prompt "${input.promptId}" from the MCP server "${input.serverId}". The prompt template is fetched from the server every time the command runs.`,
  ];
  if (def.arguments.length > 0) {
    out.push(
      "",
      "Argument values (a blank value means the user did not provide it):",
      argumentList(def, idents),
      "",
      "Replace each {{argument}} placeholder in the template below with the matching value above, then follow the resulting prompt. If a required argument is blank, ask the user for it first.",
    );
  } else {
    out.push("", "Follow the prompt below.");
  }
  out.push("", "Template:", `!\`${cliPrefix(input)} --template\``);
  return out.join("\n");
}

function agentBody(input: BuildInput, idents: string[]): string {
  const { def } = input;
  const flags = def.arguments.map((a) => `--arg ${safeArgName(a.name)}=VALUE`).join(" ");
  const out = [
    GENERATED_MARKER,
    `To use the MCP prompt "${input.promptId}" from the MCP server "${input.serverId}", run this command with the Bash tool, then follow its output as the prompt. Replace each VALUE with the matching argument value below, quoted for the shell, and leave out --arg for blank optional arguments:`,
    "",
    `    ${cliPrefix(input)}${flags ? ` ${flags}` : ""}`,
  ];
  if (def.arguments.length > 0) {
    out.push(
      "",
      "Argument values (a blank value means the user did not provide it):",
      argumentList(def, idents),
      "",
      "If a required argument is blank, ask the user for it first.",
    );
  }
  return out.join("\n");
}

function staticBody(input: BuildInput): string {
  const { def } = input;
  const required = def.arguments.filter((a) => a.required).map((a) => safeArgName(a.name));
  const out = [
    GENERATED_MARKER,
    `<!-- static snapshot of the MCP prompt "${input.promptId}" from the server "${input.serverId}"; run \`generate\` again to refresh -->`,
    "",
    input.template ?? "",
  ];
  if (required.length > 0) {
    out.push("", `Required arguments: ${required.join(", ")}. If one is blank, ask the user for it before continuing.`);
  }
  return out.join("\n");
}

/** Builds the command or skill file for one prompt. Pure: no I/O. */
export function buildFile(input: BuildInput): BuiltFile {
  const { def } = input;
  const idents = argIdents(def.arguments);
  const hint = def.arguments.map((a, i) => (a.required ? `<${idents[i]}>` : `[${idents[i]}]`)).join(" ");
  const effective: Mode = input.rejected || (input.mode === "static" && input.template === undefined) ? "agent" : input.mode;
  const head = frontmatter(input, effective, idents, hint);
  let body: string;
  if (effective === "live") body = liveBody(input, idents);
  else if (effective === "agent") body = agentBody(input, idents);
  else body = staticBody(input);
  const path =
    input.format === "skills"
      ? `skills/${input.skillDir}/SKILL.md`
      : `commands/${input.serverId}/${input.promptId}.md`;
  return { path, content: `${head}\n${body}\n`, mode: effective };
}

/**
 * Turns a rendered prompt (which still has marker values where arguments go) into the static
 * body: server text is neutralized first, then each marker becomes `$name`.
 */
export function toStaticTemplate(rendered: string, def: PromptDef, markers: Record<string, string>): string {
  const idents = argIdents(def.arguments);
  const safe = neutralizeHostSyntax(rendered, idents);
  let out = safe;
  def.arguments.forEach((a, i) => {
    const marker = markers[a.name];
    if (marker) out = out.split(marker).join(`$${idents[i] ?? ""}`);
  });
  return out;
}
