import assert from "node:assert/strict";
import { existsSync, readFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { join } from "node:path";
import { test } from "node:test";
import { runCli, simulate, tmpDir, writeStdioConfig } from "./helpers.js";

function generate(dir: string, variant: string, extra: string[] = []) {
  writeStdioConfig(dir, variant);
  return runCli(["generate", "--config", "servers.json", "--out", "out", "--bin", "echo", ...extra], { cwd: dir });
}

const read = (dir: string, rel: string): string => readFileSync(join(dir, "out", rel), "utf8");

test("generate: frontmatter and 0-based named argument mapping", (t) => {
  const dir = tmpDir(t);
  const g = generate(dir, "");
  assert.equal(g.code, 0, g.stderr);
  const file = read(dir, "commands/mock/code_review.md");
  const lines = file.split("\n");
  assert.equal(lines[0], "---");
  assert.ok(lines.includes('description: "Review a file for bugs and style"'));
  assert.ok(lines.includes('argument-hint: "<path> [focus]"'));
  assert.ok(lines.includes("arguments: [path, focus]"));
  assert.ok(lines.includes('allowed-tools: "Bash(echo get *)"'));
  assert.ok(file.includes("<!-- generated by mcp-prompt-commands; do not edit -->"));
  assert.ok(existsSync(join(dir, "out", "commands", "mock", "release-notes.md")), "name normalization");
  assert.ok(existsSync(join(dir, "out", "mcp-prompt-commands.lock.json")));

  // The documented rules: $0 is the first argument, quotes group words, no one-off shift.
  const sim = simulate(file, '"src/a b.ts" errors');
  assert.match(sim.body, /^- path \(required\): src\/a b\.ts$/m);
  assert.match(sim.body, /^- focus \(optional\): errors$/m);
  assert.ok(!/\$\d/.test(file), "no positional $N in the generated file");
  assert.ok(!file.includes("$ARGUMENTS["));
  // A missing optional argument becomes empty, and so does a missing required one (asked for by the text).
  assert.match(simulate(file, "only.ts").body, /^- focus \(optional\): $/m);

  // Skills format: directory per prompt with the name in the frontmatter.
  const s = generate(dir, "", ["--format", "skills", "--out", "out2"]);
  assert.equal(s.code, 0, s.stderr);
  const skill = readFileSync(join(dir, "out2", "skills", "mock-code_review", "SKILL.md"), "utf8");
  assert.match(skill, /^name: mock-code_review$/m);
  assert.match(skill, /^arguments: \[path, focus\]$/m);
});

test("generate: description is YAML-escaped and odd argument names become identifiers", (t) => {
  const dir = tmpDir(t);
  assert.equal(generate(dir, "weird").code, 0);
  const file = read(dir, "commands/mock/weird.md");
  const desc = /^description: (.*)$/m.exec(file)?.[1] ?? "";
  // The value is a JSON string, which is also a valid YAML double-quoted scalar.
  assert.equal(JSON.parse(desc), 'He said "hi": line one line two # not a comment, ends with colon:');
  assert.match(file, /^arguments: \[file_path\]$/m);
  assert.match(file, /^argument-hint: "<file_path>"$/m);
  assert.match(file, /^- file-path \(required\): \$file_path$/m);
});

test("security: live command line never contains user arguments", (t) => {
  const dir = tmpDir(t);
  assert.equal(generate(dir, "").code, 0);
  for (const rel of ["commands/mock/code_review.md", "commands/mock/release-notes.md"]) {
    const file = read(dir, rel);
    const shell = file.split("\n").filter((l) => l.startsWith("!"));
    assert.equal(shell.length, 1, rel);
    assert.ok(!/\$/.test(shell[0] ?? ""), `no dollar placeholder in: ${shell[0]}`);
    assert.match(shell[0] ?? "", /^!`echo get mock [a-z_-]+ --config servers\.json --template`$/);
  }
});

test("security: malicious arguments do not execute", (t) => {
  const dir = tmpDir(t);
  assert.equal(generate(dir, "").code, 0);
  const file = read(dir, "commands/mock/code_review.md");
  const evil = [
    "; touch PWNED",
    "$(touch PWNED)",
    "`touch PWNED`",
    "it's && touch PWNED",
    'say "hi" && touch PWNED',
    "line one\n!`touch PWNED`\nline three",
    "x' ; touch PWNED ; echo '",
  ];
  for (const value of evil) {
    const quote = value.includes('"') ? "'" : '"';
    const argString = `${quote}${value}${quote}`;
    const sim = simulate(file, argString, (cmd) => {
      const r = spawnSync("bash", ["-c", cmd], { cwd: dir, encoding: "utf8" });
      assert.equal(r.status, 0, r.stderr);
      return r.stdout;
    });
    assert.equal(sim.commands.length, 1, "only the generated command runs");
    assert.ok(!existsSync(join(dir, "PWNED")), `canary created by: ${JSON.stringify(value)}`);
    assert.ok(sim.body.includes(`- path (required): ${value}`), `value kept literally: ${JSON.stringify(value)}`);
  }
});

test("generate: falls back to agent-guided body when template is rejected", (t) => {
  const dir = tmpDir(t);
  const g = generate(dir, "enum");
  assert.equal(g.code, 0, g.stderr);
  assert.match(g.stderr, /rejected placeholder values for prompt "pick" \(error -32602\)/);
  const file = read(dir, "commands/mock/pick.md");
  assert.match(file, /run this command with the Bash tool/);
  assert.match(file, /^ {4}echo get mock pick --config servers\.json --arg level=VALUE$/m);
  assert.match(file, /^- level \(required\): \$level$/m);
  assert.ok(!file.split("\n").some((l) => l.startsWith("!")), "no shell block in agent mode");
  assert.match(file, /^allowed-tools: "Bash\(echo get \*\)"$/m);
  const lock = JSON.parse(read(dir, "mcp-prompt-commands.lock.json"));
  assert.equal(lock.servers.mock.prompts.pick.mode, "agent");
  // The real call with a valid value still works through get.
  const ok = runCli(["get", "mock", "pick", "--arg", "level=b", "--config", "servers.json"], { cwd: dir });
  assert.equal(ok.stdout.trim(), "Level b");
  // --mode agent never asks the server for a template.
  assert.equal(generate(dir, "", ["--mode", "agent", "--out", "out3"]).code, 0);
  assert.match(readFileSync(join(dir, "out3", "commands", "mock", "code_review.md"), "utf8"), /--arg path=VALUE --arg focus=VALUE/);
});

test("static: snapshot escapes host shell syntax and dollar placeholders", (t) => {
  const dir = tmpDir(t);
  const g = generate(dir, "hostile", ["--mode", "static"]);
  assert.equal(g.code, 0, g.stderr);
  const file = read(dir, "commands/mock/hostile.md");
  assert.ok(!/(^|\s)!`/.test(file), "no inline shell command left");
  assert.ok(!/`{3,}!/.test(file), "no shell fence left");
  assert.ok(!file.includes("allowed-tools"), "static files need no tool permission");
  assert.ok(file.includes("\\$1.00"));
  assert.ok(file.includes("\\$ARGUMENTS, first was \\$ARGUMENTS[0]"));
  assert.ok(file.includes("Literal \\$path mention"), "server text that looks like our placeholder is escaped");
  assert.ok(file.includes("the real value: $path"), "the argument slot is a real placeholder");

  // Rendering it the way Claude Code does runs no shell and leaves the server text readable.
  const sim = simulate(file, "src/x.ts", () => assert.fail("no shell command may run"));
  assert.equal(sim.commands.length, 0);
  assert.ok(sim.body.includes("Price is $1.00 and the user said $ARGUMENTS, first was $ARGUMENTS[0]."));
  assert.ok(sim.body.includes("Literal $path mention, then the real value: src/x.ts"));
  assert.ok(!existsSync(join(dir, "PWNED")));
  const lock = JSON.parse(read(dir, "mcp-prompt-commands.lock.json"));
  assert.match(lock.servers.mock.prompts.hostile.bodyHash, /^[0-9a-f]{64}$/);
});

test("static: renders offline without server", (t) => {
  const dir = tmpDir(t);
  assert.equal(generate(dir, "", ["--mode", "static"]).code, 0);
  const file = read(dir, "commands/mock/code_review.md");
  // Nothing below spawns a server or a shell: the file alone is enough.
  const sim = simulate(file, '"src/a b.ts" errors', () => assert.fail("static files have no shell"));
  assert.ok(sim.body.includes("Please review src/a b.ts focusing on errors."));
  assert.ok(sim.body.includes("### assistant\nSure. Send me the file contents."));
  assert.ok(sim.body.includes("Use 2-space indent."));
  assert.ok(sim.body.includes("Required arguments: path."));
});
